/**
 * The prose of the Economics page and of the sentences the engine writes into
 * the snapshot, in the PRD language.
 *
 * Only the narrative belongs here — headings, captions, hints, banners, the
 * warnings and notes `EconomicsService` composes. The pricing console (its
 * field labels, option labels, and the artisan command it prints) stays in
 * English: those are operator controls, not something the client reads over
 * your shoulder.
 *
 * Placeholders are `:name`, substituted with `strtr`, so a translation is free
 * to reorder them. A key missing from a language falls back to English rather
 * than rendering blank.
 */
class EconomicsStrings
{
    /** @var array<string, array<string, string>> */
    protected static array $resolved = [];

    /**
     * @return array<string, string>
     */
    public static function for(string $lang): array
    {
        $lang = in_array($lang, ArtifactLanguage::SUPPORTED, true) ? $lang : ArtifactLanguage::DEFAULT;

        if (isset(self::$resolved[$lang])) {
            return self::$resolved[$lang];
        }

        $english = self::en();

        return self::$resolved[$lang] = $lang === ArtifactLanguage::DEFAULT
            ? $english
            : array_replace($english, self::table()[$lang] ?? []);
    }

    /**
     * @param  array<string, string|int|float>  $replace
     */
    public static function line(string $lang, string $key, array $replace = []): string
    {
        $line = self::for($lang)[$key] ?? $key;

        if ($replace === []) {
            return $line;
        }

        $pairs = [];

        foreach ($replace as $name => $value) {
            $pairs[':'.$name] = (string) $value;
        }

        return strtr($line, $pairs);
    }

    /**
     * @return array<string, array<string, string>>
     */
    protected static function table(): array
    {
        return [
            'it' => self::it(),
            'es' => self::es(),
            'fr' => self::fr(),
            'de' => self::de(),
            'pt' => self::pt(),
            'nl' => self::nl(),
            'pl' => self::pl(),
        ];
    }

